static uint32_t crc32_generate(int n) {
    int      i = 0;
    uint32_t crc = 0;

    crc = n;
    for (i = 8; i >= 0; i--) {
        if (crc & 1) {
            crc = (crc >> 1) ^ 0xEDB88320;
        } else {
            crc >>= 1;
        }
    }

    return crc;
}

static uint32_t utils_crc32(const char* str, size_t strlen) {
    size_t       index = 0;
    uint32_t     table_index = 0;
    uint32_t     crcvalue = 0xFFFFFFFF;
    char         chvalue = 0;
    char         toldiff = 'a' - 'A';

    dprintdecorate("start utils_crc32");

    for (index = 0; index < strlen; index++) {
        chvalue = str[index];
        if (chvalue >= 'A' && chvalue <= 'Z') {
            chvalue = chvalue + toldiff;
        }

        table_index = (crcvalue ^ chvalue) & 0x000000FF;
        crcvalue = ((crcvalue >> 8) & 0x00FFFFFF) ^ crc32_table[table_index];
    }

    dprintdecorate("end utils_crc32");

    return ~crcvalue;
}

uint32_t utils_hashcalc(const char* str, size_t strlen) {
    return utils_crc32(str, strlen);
}

/* The hash bucket of a key, among count. The whole key is hashed, however long it is: WinCache */
/* hashed no key longer than MAX_PATH (260) characters, which put all of them in bucket 0 */
uint32_t utils_getindex(const char* key, unsigned int count) {
    uint32_t     hash = 0;
    size_t       length = 0;

    dprintdecorate("start utils_getindex");

    _ASSERT(key != NULL);
    _ASSERT(count != 0);

    length = strlen(key);
    _ASSERT(length != 0);

    hash = utils_hashcalc(key, length);
    hash = hash % count;

    dprintdecorate("end utils_getindex");

    return hash;
}

/* wstr (wlen characters) in UTF-8, in a buffer that the caller frees with alloc_pefree(), its length in *plen; NULL */
/* if it cannot be converted */
static char* utf8_from_wide(const WCHAR* wstr, int wlen, int* plen) {
    char*  buffer = NULL;
    int    len = 0;

    len = WideCharToMultiByte(CP_UTF8, 0, wstr, wlen, NULL, 0, NULL, NULL);
    if (len <= 0) {
        return NULL;
    }

    buffer = (char*)alloc_pemalloc(len);
    if (buffer == NULL) {
        return NULL;
    }

    if (WideCharToMultiByte(CP_UTF8, 0, wstr, wlen, buffer, len, NULL, NULL) != len) {
        alloc_pefree(buffer);
        return NULL;
    }

    *plen = len;
    return buffer;
}

/*
 * The application pool id of the process, which decides which processes share its cache: ucache.apppoolid (NULL in
 * UCG(apppoolid) when it is not set or empty, see MINIT), or else the APP_POOL_ID environment variable that IIS sets.
 * Sets *phash to the first 8 bytes of the SHA-1 of the id in UTF-8, with A-Z taken as a-z (IIS pool names are case
 * insensitive), and returns 1; returns 0 when the process has no application pool id. The id is hashed in UTF-8
 * whatever it comes from, so that ucache.apppoolid=X and APP_POOL_ID=X give the same cache: APP_POOL_ID is read as
 * Unicode, and ucache.apppoolid is taken as it is when it is valid UTF-8 (php.ini saved in UTF-8), and otherwise as
 * text of the ANSI code page (an ANSI php.ini, or -d, whose argument PHP gets in that code page). WinCache reduced the
 * id to one of 899999 numbers (a CRC modulo 899999), so that different pools could share a cache, and read
 * APP_POOL_ID in the ANSI code page, where names that differ only in other characters are the same
 */
int utils_apoolhash(uint64_t* phash) {
    int            retval = 0;
    const char*    name = UCG(apppoolid);
    size_t         namelen = 0;
    WCHAR*         wbuffer = NULL;
    char*          buffer = NULL;
    DWORD          wsize = 0;
    DWORD          wlen = 0;
    int            len = 0;
    size_t         index = 0;
    size_t         count = 0;
    uint64_t       hash = 0;
    unsigned char  chunk[64];
    unsigned char  digest[20];
    PHP_SHA1_CTX   context;

    dprintverbose("start utils_apoolhash");

    _ASSERT(phash != NULL);

    /* Empty is no id, also if MINIT did not make it NULL first */
    if (name != NULL && name[0] != '\0') {
        dprintverbose("using apppoolid");
        namelen = strlen(name);

        /* Not UTF-8: from the ANSI code page to UTF-8, through UTF-16. If that fails (memory), the bytes are hashed */
        /* as they are, which still makes a group of their own */
        if (MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS, name, (int)namelen, NULL, 0) == 0) {
            wlen = (DWORD)MultiByteToWideChar(CP_ACP, 0, name, (int)namelen, NULL, 0);
            if (wlen > 0) {
                wbuffer = (WCHAR*)alloc_pemalloc(wlen * sizeof(WCHAR));
            }

            if (wbuffer != NULL && MultiByteToWideChar(CP_ACP, 0, name, (int)namelen, wbuffer, (int)wlen) == (int)wlen) {
                buffer = utf8_from_wide(wbuffer, (int)wlen, &len);
            }

            if (buffer != NULL) {
                name = buffer;
                namelen = (size_t)len;
            }
        }
    } else {
        /* Its size with the terminating null, in characters: 0 when it is not set, 1 when it is empty */
        wsize = GetEnvironmentVariableW(L"APP_POOL_ID", NULL, 0);
        if (wsize <= 1) {
            goto Finished;
        }

        wbuffer = (WCHAR*)alloc_pemalloc(wsize * sizeof(WCHAR));
        if (wbuffer == NULL) {
            goto Finished;
        }

        /* Its length without the terminating null */
        wlen = GetEnvironmentVariableW(L"APP_POOL_ID", wbuffer, wsize);
        if (wlen == 0 || wlen >= wsize) {
            goto Finished;
        }

        buffer = utf8_from_wide(wbuffer, (int)wlen, &len);
        if (buffer == NULL) {
            goto Finished;
        }

        name = buffer;
        namelen = (size_t)len;
    }

    /* SHA-1 of the id with A-Z taken as a-z, a chunk at a time */
    PHP_SHA1Init(&context);
    while (index < namelen) {
        for (count = 0; count < sizeof(chunk) && index < namelen; count++, index++) {
            chunk[count] = (unsigned char)name[index];
            if (chunk[count] >= 'A' && chunk[count] <= 'Z') {
                chunk[count] += 'a' - 'A';
            }
        }

        PHP_SHA1Update(&context, chunk, count);
    }
    PHP_SHA1Final(digest, &context);

    for (index = 0; index < sizeof(hash); index++) {
        hash = (hash << 8) | digest[index];
    }

    *phash = hash;
    retval = 1;

Finished:

    if (buffer != NULL) {
        alloc_pefree(buffer);
        buffer = NULL;
    }

    if (wbuffer != NULL) {
        alloc_pefree(wbuffer);
        wbuffer = NULL;
    }

    dprintverbose("end utils_apoolhash");

    return retval;
}

/*
 * Milliseconds from past to present, two GetTickCount64() values: they count from the start of
 * Windows and do not wrap (GetTickCount() wrapped every 49.7 days).  0 if past is the later one:
 * a time that another process stored after this one read the clock.
 */
ULONGLONG utils_ticksdiff(ULONGLONG present, ULONGLONG past) {
    ULONGLONG ticksdiff = 0;

    if (present > past) {
        ticksdiff = present - past;
    }

    return ticksdiff;
}

/*
 * Caller must free returned string using alloc_pefree( ptr ).
 */
char* utils_build_temp_filename(char* suffix) {
    char*        temp_file = NULL;
    const char*  temp_dir = UCG(filemapdir);
    size_t       filename_len;

    if (!temp_dir) {
        goto Finished;
    }

    filename_len = strlen(temp_dir);

    // TODO: Make sure trailing char is not IS_SLASH()

    filename_len += strlen(suffix);
    filename_len++;     /* DEFAULT_SLASH separator */
    filename_len += TEMP_FILE_PREFIX_CHARS;
    filename_len++;     /* terminating NULL */

    temp_file = alloc_pemalloc(filename_len);
    if (!temp_file) {
        error_setlasterror();
        goto Finished;
    }

    _snprintf_s(temp_file, filename_len, filename_len - 1, "%s\\ucache_%s.tmp", temp_dir, suffix);

Finished:
    return temp_file;
}

/*
 * If this succeeds, then caller must ReleaseMutex on the returned pinit_event
 * handle.
 */
int utils_create_init_event(
    char* prefix,
    char* name,
    HANDLE* pinit_event,
    unsigned char* pisfirst
) {
    int                    result = NONFATAL;
    int                    len = 0;
    char                   evtname[MAX_PATH];
    DWORD                  ret = 0;
    HANDLE                 hinitdone = NULL;
    unsigned char          isfirst = 1;

    *pinit_event = NULL;

    len = _snprintf_s(evtname, MAX_PATH, MAX_PATH - 1, "%s%s", prefix, name);
    if (len == -1) {
        result = FATAL_ALLOC_INIT_EVENT;
        goto Finished;
    }

    hinitdone = CreateMutex(NULL, TRUE, evtname);
    if (hinitdone == NULL) {
        error_setlasterror();
        dprintcritical("Failed to create event %s", evtname);
        result = FATAL_ALLOC_INIT_EVENT;
        goto Finished;
    }

    if (GetLastError() == ERROR_ALREADY_EXISTS) {
        isfirst = 0;

        /* Wait for other process to initialize completely */
        ret = WaitForSingleObject(hinitdone, MAX_INIT_EVENT_WAIT);

        if (ret == WAIT_TIMEOUT) {
            /* Recorded as the Windows error of the failure, which the startup warning reports as a timeout */
            SetLastError(WAIT_TIMEOUT);
            error_setlasterror();
            dprintcritical("Timed out waiting for other process to release %s", evtname);
            result = FATAL_ALLOC_INIT_EVENT;
            goto Finished;
        }

        if (ret == WAIT_FAILED) {
            dprintcritical("Failed waiting for other process to release %s: (%d)", evtname, error_setlasterror());
            result = FATAL_ALLOC_INIT_EVENT;
            goto Finished;
        }

        /* The mutex is this process's all the same. The callers do not go by who owned it: they check */
        /* the memory the process that died left (its init mark), as after one that completed */
        if (ret == WAIT_ABANDONED) {
            dprintimportant("Acquired abandoned mutex %s: the process that owned it died", evtname);
        }
    }

    *pinit_event = hinitdone;
    *pisfirst = isfirst;

Finished:
    if (FAILED(result)) {
        if (hinitdone) {
            CloseHandle(hinitdone);
            hinitdone = NULL;
        }
    }
    return result;
}

