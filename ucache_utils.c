/* APP_POOL_ID as utils_get_apppool_name() read it (ANSI, for LookupAccountName), for the life of the process. Not in */
/* UCG(apppoolid), which stays the setting that utils_apoolhash() reads */
static PSTR g_apppoolname = NULL;

/* Caller must NOT free the returned string */
const char*
utils_get_apppool_name() {
    unsigned int buflen;
    PSTR         szAppPoolName = NULL;
    int          ret = 0;

    if (UCG(apppoolid)) {
        return UCG(apppoolid);
    }

    if (g_apppoolname) {
        return g_apppoolname;
    }

    /* Get app pool ID (ANSI, as LookupAccountName takes it) */
    buflen = GetEnvironmentVariableA("APP_POOL_ID", NULL, 0);
    if (buflen == 0) {
        /* No app pool.  Don't do anything */
        goto Finished;
    }

    szAppPoolName = (PSTR)alloc_pemalloc(buflen + 1);
    if (szAppPoolName == NULL) {
        ret = FATAL_OUT_OF_MEMORY;
        goto Finished;
    }

    buflen = GetEnvironmentVariable("APP_POOL_ID", szAppPoolName, buflen + 1);
    if (buflen == 0) {
        ret = FATAL_UNEXPECTED_DATA;
        goto Finished;
    }

    g_apppoolname = szAppPoolName;

Finished:
    if (FAILED(ret)) {
        if (szAppPoolName) {
            alloc_pefree(szAppPoolName);
            szAppPoolName = NULL;
        }
    }

    return szAppPoolName;
}

/* IIS App Pool Functions */

int
utils_set_apppool_acl(
    char* filename
) {
    int    ret = 0;
    PCSTR  szAppPoolName = NULL;
    PSTR   szNewSddlAcl = NULL;
    PSID   pAppPoolSid = NULL;
    PSID   pUserSid = NULL;
    PSTR   szAppPoolSid = NULL;
    PSTR   szUserSid = NULL;
    size_t sddlLen = 0;

    /* Get app pool name */
    szAppPoolName = utils_get_apppool_name();
    if (!szAppPoolName) {
        /* No app pool.  Don't do anything */
        goto Finished;
    }

    /* Get app pool SID */
    ret = GetAppPoolSid(szAppPoolName, &pAppPoolSid);
    if (FAILED(ret)) {
        goto Finished;
    }

    /* Convert SID to String */
    if (!ConvertSidToStringSidA(pAppPoolSid, &szAppPoolSid)) {
        error_setlasterror();
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }

    /*
     * Get Token for the current user.
     * Free the token user with the FreeTokenUserSid API when done.
     */

    ret = GetUserSid(&pUserSid);
    if (FAILED(ret)) {
        goto Finished;
    }

    /* Convert SID to String */
    if (!ConvertSidToStringSidA(pUserSid, &szUserSid)) {
        error_setlasterror();
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }


    /* Construct SDDL string for file ACL */
    /* ACL: SYSTEM:Full, ADMINISTRATORS:Full, AppPool:Full */
    sddlLen = g_cchSddlTemplate;  /* includes terminating NULL */
    sddlLen += strlen(szAppPoolSid);
    sddlLen += strlen(szUserSid);
    szNewSddlAcl = (PSTR)alloc_pemalloc(sddlLen);
    if (!szNewSddlAcl) {
        ret = FATAL_OUT_OF_MEMORY;
        goto Finished;
    }

    sprintf_s(szNewSddlAcl, sddlLen, g_sddlTemplate, szAppPoolSid, szUserSid);

    /* set on filename */
    ret = SetFileDacl(szNewSddlAcl, filename);

Finished:

    if (szNewSddlAcl) {
        alloc_pefree(szNewSddlAcl);
        szNewSddlAcl = NULL;
    }

    if (szAppPoolSid) {
        LocalFree(szAppPoolSid);
        szAppPoolSid = NULL;
    }

    if (szUserSid) {
        LocalFree(szUserSid);
        szUserSid = NULL;
    }

    if (pAppPoolSid) {
        alloc_pefree(pAppPoolSid);
        pAppPoolSid = NULL;
    }

    if (pUserSid) {
        alloc_pefree(pUserSid);
        pUserSid = NULL;
    }

    return ret;
}

/*****************************************************************************

 Routine Description:

    Sets the DACL on the specified file.

 Arguments:

    pszSddl - SDDL representation of DACL
    pszFilePath - complete file path

 Returns:

    NONFATAL - Success
    FATAL_ACL_FAILED - Could not set the ACL on the file.

*****************************************************************************/
int
SetFileDacl(
    PSTR pszSddl,
    PSTR pszFilePath
) {
    int                 ret = NONFATAL;
    SECURITY_ATTRIBUTES secAttr;
    BOOL                fDaclPresent = FALSE;
    BOOL                fDaclDefaulted = FALSE;
    PACL                pAcl = NULL;
    DWORD               dwStatus = 0;
    WCHAR               pwszSddl[1024];

    SecureZeroMemory(&secAttr, sizeof(secAttr));

    ret = MultiByteToWideChar(CP_UTF8,
        MB_ERR_INVALID_CHARS,
        pszSddl,
        -1,
        pwszSddl,
        1024);
    if (0 == ret) {
        error_setlasterror();
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }

    ret = NONFATAL;

    if (!ConvertStringSecurityDescriptorToSecurityDescriptorW(
        pwszSddl,
        SDDL_REVISION_1,
        &(secAttr.lpSecurityDescriptor),
        NULL)) {
        error_setlasterror();
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }

    secAttr.nLength = sizeof(secAttr);
    secAttr.bInheritHandle = FALSE;

    if (!GetSecurityDescriptorDacl(secAttr.lpSecurityDescriptor,
        &fDaclPresent,
        &pAcl,
        &fDaclDefaulted)) {
        error_setlasterror();
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }

    if (fDaclPresent) {
        dwStatus = SetNamedSecurityInfoA(pszFilePath,
            SE_FILE_OBJECT,
            DACL_SECURITY_INFORMATION | PROTECTED_DACL_SECURITY_INFORMATION,
            NULL,
            NULL,
            pAcl,
            NULL);

        if (dwStatus != ERROR_SUCCESS) {
            error_setlasterror();
            ret = FATAL_ACL_FAILED;
            goto Finished;
        }
    }

Finished:

    if (secAttr.lpSecurityDescriptor != NULL) {
        LocalFree(secAttr.lpSecurityDescriptor);
        secAttr.lpSecurityDescriptor = NULL;
    }

    return ret;
}

/* callers must free returned PSID with alloc_pefree() */
int
GetAppPoolSid(
    PCSTR szAppPoolName,
    PSID* ppSid
) {
    int          ret = 0;
    char*        szAccountName = NULL;
    char*        szDomainName = NULL;
    size_t       cchAccountName = 0;
    DWORD        sidLength = 0;
    DWORD        domainNameLength = 0;
    SID_NAME_USE sidNameUse;
    PSID         pSid = NULL;

    /* build the app pool account name */
    /* "IIS APPPOOL\<AppPoolName>" */
    cchAccountName = strlen(szAppPoolName) + 1 + SC_APP_POOL_DOMAIN_NAME_LEN;
    szAccountName = alloc_pemalloc(cchAccountName + 1);
    if (!szAccountName) {
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }

    sprintf_s(szAccountName, cchAccountName + 1, "%s\\%s", SC_APP_POOL_DOMAIN_NAME, szAppPoolName);

    if (!LookupAccountName(
        NULL,                              // lpSystemName
        szAccountName,                     // lpAccountName
        NULL,                              // Sid
        &sidLength,                        // cbSid
        NULL,                              // ReferencedDomainName
        &domainNameLength,                 // cchReferencedDomainName
        &sidNameUse                        // peUse
    )) {
        if (GetLastError() != ERROR_INSUFFICIENT_BUFFER) {
            error_setlasterror();
            ret = WARNING_APPPOOL_NAME_NOT_FOUND;
            goto Finished;
        }

        pSid = (PSID)alloc_pemalloc(sidLength);
        if (!pSid) {
            ret = FATAL_OUT_OF_MEMORY;
            goto Finished;
        }

        szDomainName = (char*)alloc_pemalloc(domainNameLength);
        if (!szDomainName) {
            ret = FATAL_OUT_OF_MEMORY;
            goto Finished;
        }

        if (!LookupAccountName(
            NULL,                              // lpSystemName
            szAccountName,                     // lpAccountName
            pSid,                              // Sid
            &sidLength,                        // cbSid
            szDomainName,                      // ReferencedDomainName
            &domainNameLength,                 // cchReferencedDomainName
            &sidNameUse                        // peUse
        )) {
            error_setlasterror();
            ret = FATAL_ACL_FAILED;
            goto Finished;
        }
    }

    *ppSid = pSid;

Finished:

    if (szAccountName) {
        alloc_pefree(szAccountName);
        szAccountName = NULL;
    }

    if (szDomainName) {
        alloc_pefree(szDomainName);
        szDomainName = NULL;
    }

    return ret;
}

/* callers must free returned PSID with alloc_pefree() */
int
GetUserSid(
    PSID* ppSid
) {
    int                  ret = SUCCESS;
    BOOL                 fRet = FALSE;
    HANDLE               hProcessToken = NULL;
    TOKEN_USER*          pTokenUser = NULL;
    PSID                 pSid = NULL;
    DWORD                cbSid = 0;
    DWORD                cbSize = 0;

    /*
     * Get Current User SID
     */

    if (!OpenProcessToken(GetCurrentProcess(), GENERIC_READ, &hProcessToken)) {
        error_setlasterror();
        ret = FATAL_ACCESS_DENIED;
        goto Finished;
    }

    /*
     * Get Token for the current user.
     * Free the token user with the FreeTokenUserSid API when done.
     */

    fRet = GetTokenInformation(hProcessToken,
        TokenUser,
        NULL,
        0,
        &cbSize);
    if (FALSE == fRet) {
        if (ERROR_INSUFFICIENT_BUFFER != GetLastError()) {
            error_setlasterror();
            ret = FATAL_ACL_FAILED;
            goto Finished;
        }
    }

    pTokenUser = (TOKEN_USER*)alloc_pemalloc(cbSize);
    if (NULL == pTokenUser) {
        ret = FATAL_OUT_OF_MEMORY;
        goto Finished;
    }

    fRet = GetTokenInformation(hProcessToken,
        TokenUser,
        pTokenUser,
        cbSize,
        &cbSize);
    if (FALSE == fRet) {
        error_setlasterror();
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }


    cbSid = GetLengthSid(pTokenUser->User.Sid);
    pSid = (PSID)alloc_pemalloc(cbSid);
    if (!pSid) {
        ret = FATAL_OUT_OF_MEMORY;
        goto Finished;
    }

    if (!CopySid(cbSid, pSid, pTokenUser->User.Sid)) {
        error_setlasterror();
        ret = FATAL_ACL_FAILED;
        goto Finished;
    }

    /* Transfer ownership of memory to caller */
    *ppSid = pSid;
    pSid = NULL;

Finished:

    if (pTokenUser) {
        alloc_pefree(pTokenUser);
        pTokenUser = NULL;
    }

    if (pSid) {
        alloc_pefree(pSid);
        pSid = NULL;
    }

    return ret;
}

/*
 * Impersonation utils
 */

int utils_revert_if_necessary(HANDLE* phOriginalToken) {
    int    result = NONFATAL;
    HANDLE hOriginalToken = NULL;

    /*
     * RevertToSelf if needed
     */
    if (OpenThreadToken(GetCurrentThread(), /* thread handle whose access token is opened */
        TOKEN_IMPERSONATE,                  /* desired access */
        TRUE,                               /* open as self (access check made against process) */
        &hOriginalToken))                   /* out token handle */
    {
        _ASSERT(hOriginalToken != NULL);
        if (!RevertToSelf()) {
            error_setlasterror();
            result = FATAL_FILEMAP_REVERT_FAILED;
            goto Finished;
        }
    } else {
        /* No token: the thread does not impersonate. That is no failure, so it is not recorded as the last error, */
        /* which a later failure reports (see startup_failure_warning) */
        if (ERROR_NO_TOKEN == GetLastError()) {
            hOriginalToken = NULL;
        } else {
            error_setlasterror();
            result = FATAL_FILEMAP_REVERT_FAILED;
            goto Finished;
        }
    }

Finished:

    *phOriginalToken = hOriginalToken;

    return result;
}

void utils_reimpersonate_if_necessary(HANDLE hOriginalToken) {
    if (hOriginalToken != NULL) {
        if (!SetThreadToken(NULL, hOriginalToken)) {
            error_setlasterror();
        }

        CloseHandle(hOriginalToken);
    }
}

const char* utils_get_typename(zend_uchar type) {
    const char* valuetype;

    switch (type) {
        case IS_UNDEF:
            valuetype = "undef";
            break;
        case IS_NULL:
            valuetype = "null";
            break;
        case IS_TRUE:
        case IS_FALSE:
            valuetype = "bool";
            break;
        case IS_LONG:
            valuetype = "long";
            break;
        case IS_DOUBLE:
            valuetype = "double";
            break;
        case IS_STRING:
            valuetype = "string";
            break;
        case IS_ARRAY:
            valuetype = "array";
            break;
        case IS_OBJECT:
            valuetype = "object";
            break;
        case IS_REFERENCE:
            valuetype = "reference";
            break;
#if PHP_VERSION_ID < 70300
        case IS_CONSTANT:   /* removed in PHP 7.3 */
#endif
        case IS_CONSTANT_AST:
            valuetype = "constant";
            break;
#if ZEND_MODULE_API_NO >= 20160303
        case IS_VOID:
            valuetype = "void";
            break;
#endif /* ZEND_MODULE_API_NO */
        default:
            valuetype = "unknown";
            break;
    }

    return valuetype;
}

/*
 * The largest prime that is not greater than value (2 below 3), by trial division: it runs once
 * per process, when the cache is opened, on values up to about 2 million, where it takes
 * microseconds.  WinCache picked from a table of primes that doubled from one to the next, so a
 * cache could get as little as half the buckets it was meant to have.
 */
unsigned int utils_get_prime_less_than(size_t value) {
    unsigned int candidate = 0;
    unsigned int divisor = 0;

    if (value < 3) {
        return 2;
    }

    /* The largest odd number not greater than value */
    candidate = (value > UINT_MAX) ? UINT_MAX : (unsigned int)value;
    if ((candidate & 1) == 0) {
        candidate--;
    }

    for (;; candidate -= 2) {
        for (divisor = 3; divisor <= candidate / divisor; divisor += 2) {
            if (candidate % divisor == 0) {
                break;
            }
        }

        if (divisor > candidate / divisor) {
            return candidate;
        }
    }
}
